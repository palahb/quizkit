/** Every generated file: repository path → content. */
export function buildPromptDocs(): Record<string, string> {
  const files: Record<string, string> = {
    'docs/prompts/README.md': promptIndex(),
    'docs/format.md': FORMAT.en,
    'docs/format.tr.md': FORMAT.tr,
  };
  for (const lang of LANGS) {
    for (const p of getPrompts(lang)) files[`docs/prompts/${lang}/${p.id}.md`] = promptPage(lang, p.id, p.title, p.description, p.body);
    files[`examples/quiz.${lang}.json`] = json(PROMPT_EXAMPLES[lang].single);
    files[`examples/math.${lang}.json`] = json(PROMPT_EXAMPLES[lang].math);
    files[`examples/terms.${lang}.json`] = json(PROMPT_EXAMPLES[lang].terms);
    files[`examples/collection.${lang}.json`] = json(PROMPT_EXAMPLES[lang].course);
  }
  return files;
}
