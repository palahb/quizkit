function promptPage(lang: PromptLanguage, id: string, title: string, description: string, body: string): string {
  const other = lang === 'en' ? 'tr' : 'en';
  const switcher = lang === 'en' ? `[Türkçe](../${other}/${id}.md)` : `[English](../${other}/${id}.md)`;
  // Four backticks: the prompt text itself mentions ``` and must not close the block.
  return [GENERATED, '', `# ${title}`, '', description, '', switcher, '', COPY_HINT[lang], '', '````text', body, '````', ''].join('\n');
}

