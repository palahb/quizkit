// Post-export step: writes dist/sw.js (offline precache service worker) and dist/404.html.
// Run: npm run build:sw (part of npm run build:web)
//
// 404.html is a copy of index.html. GitHub Pages serves it for unknown paths, so a refreshed
// deep link shows the app shell. Caveat: Pages answers with HTTP status 404 for those requests;
// the page still renders, but only the service worker (navigations -> cached index.html) makes
// deep links fully clean once the app has been installed/visited.
import { copyFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

export type FileEntry = { path: string; size: number };

const EXCLUDED = new Set(['sw.js', '404.html', '.DS_Store']);

/** Every file under dir as a posix path relative to dir, sorted; sw.js and 404.html are never precached. */
export function listEntries(dir: string, prefix = ''): FileEntry[] {
  const out: FileEntry[] = [];
  for (const name of readdirSync(join(dir, prefix)).sort()) {
    const rel = prefix ? `${prefix}/${name}` : name;
    if (name === '.DS_Store' || (!prefix && EXCLUDED.has(name))) continue;
    const stat = statSync(join(dir, rel));
    if (stat.isDirectory()) out.push(...listEntries(dir, rel));
    else out.push({ path: rel, size: stat.size });
  }
  return out;
}

export function listFiles(dir: string): string[] {
  return listEntries(dir).map((e) => e.path);
}

/** Short deterministic hash of the sorted `path:size` list. */
export function computeBuildId(entries: FileEntry[]): string {
  const lines = entries.map((e) => `${e.path}:${e.size}`).sort();
  return createHash('sha256').update(lines.join('\n')).digest('hex').slice(0, 10);
}

/** files are relative to the SW scope ('' = the scope root itself). */
export function buildSw(files: string[], buildId: string): string {
  return `// Generated by scripts/build-sw.ts - do not edit.
'use strict';
var CACHE = ${JSON.stringify(`quizkit-${buildId}`)};
var FILES = ${JSON.stringify(files)};
var SCOPE = self.registration.scope;
var INDEX = new URL('index.html', SCOPE).href;

// Atomic precache: any failed fetch rejects the install, so the previous worker and cache keep serving.
self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      return Promise.all(
        FILES.map(function (path) {
          var url = new URL(path, SCOPE).href;
          return fetch(url, { cache: 'reload' }).then(function (res) {
            if (!res || !res.ok) throw new Error('precache failed: ' + url + ' (' + (res && res.status) + ')');
            return cache.put(url, res);
          });
        })
      );
    }).then(function () {
      return self.skipWaiting();
    })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(
        keys
          .filter(function (key) {
            return key.indexOf('quizkit-') === 0 && key !== CACHE;
          })
          .map(function (key) {
            return caches.delete(key);
          })
      );
    }).then(function () {
      return self.clients.claim();
    })
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;
  var url = new URL(request.url);
  if (url.href.indexOf(SCOPE) !== 0) return; // cross-origin or outside the scope
  var key = request.mode === 'navigate' ? INDEX : url.origin + url.pathname + url.search;
  event.respondWith(
    caches.open(CACHE).then(function (cache) {
      return cache.match(key).then(function (hit) {
        return hit || fetch(request);
      });
    })
  );
});
`;
}

function main(): void {
  const dist = join(__dirname, '..', 'dist');
  const entries = listEntries(dist);
  if (!entries.some((e) => e.path === 'index.html')) throw new Error('dist/index.html missing; run expo export first');
  const buildId = computeBuildId(entries);
  writeFileSync(join(dist, 'sw.js'), buildSw(['', ...entries.map((e) => e.path)], buildId));
  copyFileSync(join(dist, 'index.html'), join(dist, '404.html'));
  console.log(`wrote dist/sw.js (${entries.length + 1} precached urls, build ${buildId}) and dist/404.html`);
}

if (require.main === module) main();
