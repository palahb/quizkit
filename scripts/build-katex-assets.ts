// Generates src/components/math/katexCss.generated.ts: KaTeX CSS with every font
// inlined as a base64 woff2 data URI, so math renders with no file or network access.
// Run: npm run build:katex
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = join(__dirname, '..', 'node_modules', 'katex', 'dist');
const css = readFileSync(join(dist, 'katex.min.css'), 'utf8');

const inlined = css.replace(/src:([^;}]+)/g, (_match, sources: string) => {
  const woff2 = /url\(fonts\/([^)]+\.woff2)\)/.exec(sources);
  if (!woff2) return `src:${sources}`;
  const data = readFileSync(join(dist, 'fonts', woff2[1])).toString('base64');
  return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
});

if (/url\(fonts\//.test(inlined)) throw new Error('Some KaTeX font URLs were not inlined');

const out = join(__dirname, '..', 'src', 'components', 'math', 'katexCss.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/build-katex-assets.ts. Do not edit.\nexport const KATEX_CSS = ${JSON.stringify(inlined)};\n`,
);
console.log(`wrote ${out} (${Math.round(inlined.length / 1024)} KB)`);
